// Package jrsonnet provides Go bindings for the jrsonnet Jsonnet evaluator.
package jrsonnet

/*
#cgo CFLAGS: -I${SRCDIR}/include
#cgo darwin,arm64 LDFLAGS: -L${SRCDIR}/lib/aarch64-apple-darwin      -ljrsonnet_go -lm -ldl
#cgo linux,arm64 LDFLAGS:  -L${SRCDIR}/lib/aarch64-unknown-linux-gnu -ljrsonnet_go -lm -ldl -lpthread
#cgo linux,amd64 LDFLAGS:  -L${SRCDIR}/lib/x86_64-unknown-linux-gnu  -ljrsonnet_go -lm -ldl -lpthread
#include "jrsonnet_go.h"
*/
import "C"

import (
	"errors"
	"math"
	"runtime"
	"runtime/cgo"
	"strings"
	"sync"
)

// vmTask is a unit of work dispatched to the VM's dedicated OS thread.
type vmTask struct {
	fn   func()
	done chan struct{}
}

// VM is a Jsonnet virtual machine. It is safe for concurrent use from
// multiple goroutines — calls are serialised onto the VM's dedicated OS thread.
//
// Each VM owns one OS thread for its entire lifetime. This is required because
// jrsonnet relies on thread-local state (the string interner pool and several
// thread_local IStr caches generated by jrsonnet-macros) that cannot be safely
// migrated between OS threads. Closing the VM terminates that goroutine, which
// in turn lets the underlying OS thread exit and tear down its TLS cleanly.
type VM struct {
	vm *C.VM

	tasks    chan vmTask   // submitted work for the dedicated thread
	finished chan struct{} // closed by the dedicated goroutine on exit

	mu     sync.Mutex // protects closed and serialises sends on tasks
	closed bool

	// gcInterval is the number of evaluations between cycle collections, 0
	// for none. evaluations counts them since the last one, and is only used
	// on the VM's thread.
	gcInterval  uint
	evaluations uint

	// cgo.Handle references for callback cleanup. The handle values are
	// passed to Rust as opaque integers (uintptr_t), so there is no
	// C-allocated context to free — only the handles themselves.
	importHandle  *cgo.Handle
	nativeHandles []cgo.Handle
}

// New creates a new Jsonnet VM and applies the given options.
//
// A dedicated OS thread is spawned for the VM. All subsequent operations
// (including Close) run on that thread.
func New(opts ...Option) (*VM, error) {
	c, err := newConfig(opts)
	if err != nil {
		return nil, err
	}
	v := &VM{
		tasks:      make(chan vmTask),
		finished:   make(chan struct{}),
		gcInterval: c.gcInterval,
	}

	started := make(chan error, 1)
	go v.runLoop(c, started)
	if err := <-started; err != nil {
		// runLoop has already torn down and closed v.finished.
		<-v.finished
		return nil, err
	}
	return v, nil
}

// runLoop is the dedicated goroutine that owns the VM's OS thread.
// It creates the VM, then processes tasks until the tasks channel is closed
// by Close.
func (v *VM) runLoop(c *config, started chan<- error) {
	// Pin this goroutine to its OS thread for its entire lifetime.
	// We intentionally do NOT call UnlockOSThread: when this goroutine
	// returns, the Go runtime terminates the underlying OS thread, which
	// runs Rust's TLS destructors (interner pool, gcmodule, NAMES caches)
	// in the order jrsonnet expects.
	runtime.LockOSThread()

	if err := v.create(c); err != nil {
		started <- err
		close(v.finished)
		return
	}
	started <- nil

	for task := range v.tasks {
		task.fn()
		close(task.done)
	}

	// Channel was closed by Close(); tear the VM down on this same thread.
	C.jrsonnet_go_vm_destroy(v.vm)
	C.jrsonnet_go_gc_collect()
	v.vm = nil
	close(v.finished)
}

// create creates the VM from c, on the VM's thread.
func (v *VM) create(c *config) error {
	if c.importer != nil {
		h := cgo.NewHandle(c.importer)
		v.importHandle = &h
		v.vm = makeVMWithImporter(h)
	} else {
		var jpaths strings.Builder
		for _, p := range c.jpaths {
			jpaths.WriteString(p)
			jpaths.WriteByte(0) // WithJPath rejects paths containing NUL
		}
		v.vm = C.jrsonnet_go_vm_make(jpaths.String())
	}
	if v.vm == nil {
		if v.importHandle != nil {
			v.importHandle.Delete()
		}
		return errors.New("jrsonnet: failed to create the VM")
	}

	if c.maxStack != nil {
		C.jrsonnet_go_max_stack(v.vm, cUint(*c.maxStack))
	}
	if c.maxTrace != nil {
		C.jrsonnet_go_max_trace(v.vm, cUint(*c.maxTrace))
	}
	C.jrsonnet_go_string_output(v.vm, cFlag(c.stringOutput))
	C.jrsonnet_go_trailing_newline(v.vm, cFlag(c.trailingNewline))
	return nil
}

// cUint converts u, saturating instead of wrapping.
func cUint(u uint) C.uint {
	return C.uint(min(u, math.MaxUint32))
}

func cFlag(b bool) C.uint {
	if b {
		return 1
	}
	return 0
}

// Close destroys the VM and frees all resources.
// It is safe to call Close multiple times.
func (v *VM) Close() error {
	v.mu.Lock()
	if v.closed {
		v.mu.Unlock()
		return nil
	}
	v.closed = true
	close(v.tasks)
	v.mu.Unlock()

	// Wait for the dedicated goroutine to finish destroying the VM and
	// release its OS thread.
	<-v.finished

	// Release cgo handles. Safe to do here because the dedicated thread is
	// gone and no callback can still fire.
	if v.importHandle != nil {
		v.importHandle.Delete()
	}
	for _, h := range v.nativeHandles {
		h.Delete()
	}

	return nil
}
